export const ALL_PAGES = ALL_PAGE_IDS.map((id) => PAGES_META[id]);

export function getPageByUrl(url: string): PageMeta | undefined {
  const normalized = url.endsWith("/") ? url : `${url}/`;
  return ALL_PAGES.find((p) => p.url === normalized);
}

export function getPagesByCluster(cluster: PageMeta["cluster"]): PageMeta[] {
  return ALL_PAGES.filter((p) => p.cluster === cluster);
}

